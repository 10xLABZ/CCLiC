export const generateCityJobs = (cityName) => {
  // Select 12 random jobs from the 24 templates
  const shuffled = [...JOB_TEMPLATES].sort(() => Math.random() - 0.5);
  const selected = shuffled.slice(0, 12);
  
  const tierCoverCost = { "Street": 1, "Hustle": 2, "Scheme": 3, "High Stakes": 4 };
  return selected.map(job => ({
    ...job,
    name: `${job.name} (${cityName})`,
    opCoverCost: tierCoverCost[job.tier] || 1
  }));
};